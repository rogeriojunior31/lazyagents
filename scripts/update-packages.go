//go:build ignore

// update-packages renders binary recipes from a published release's SHA256SUMS.
// Run from the repository root; it never downloads or publishes anything.
package main

import (
	"bufio"
	"bytes"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"text/template"

	"github.com/rogeriojunior31/lazyagents/internal/fsutil"
)

func main() {
	version := flag.String("version", "", "published version without v (for example 0.2.3)")
	sums := flag.String("checksums", "", "local SHA256SUMS downloaded from that release")
	out := flag.String("out", "packaging", "recipe output directory")
	flag.Parse()
	if err := updatePackages(*version, *sums, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var packageVersion = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$`)

func packageSums(version string, r io.Reader) (map[string]string, error) {
	if !packageVersion.MatchString(version) {
		return nil, fmt.Errorf("version must be a stable major.minor.patch without v")
	}
	want := map[string]string{}
	for _, platform := range []string{"darwin_amd64", "darwin_arm64", "linux_amd64", "linux_arm64", "windows_amd64"} {
		ext := ".tar.gz"
		if platform == "windows_amd64" {
			ext = ".zip"
		}
		want["lazyagents_"+version+"_"+platform+ext] = platform
	}
	sums := map[string]string{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 0 {
			continue
		}
		if len(fields) != 2 {
			return nil, fmt.Errorf("invalid SHA256SUMS row")
		}
		hash, name := fields[0], strings.TrimPrefix(fields[1], "*")
		platform, ok := want[name]
		if !ok {
			return nil, fmt.Errorf("unexpected release archive %q", name)
		}
		if _, ok := sums[platform]; ok {
			return nil, fmt.Errorf("duplicate release archive %q", name)
		}
		decoded, err := hex.DecodeString(hash)
		if err != nil || len(decoded) != 32 {
			return nil, fmt.Errorf("invalid SHA256 for %s", name)
		}
		sums[platform] = strings.ToLower(hash)
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("reading checksums: %w", err)
	}
	if len(sums) != len(want) {
		return nil, fmt.Errorf("SHA256SUMS must contain all five archives for %s", version)
	}
	return sums, nil
}

func updatePackages(version, checksumPath, out string) error {
	f, err := os.Open(checksumPath)
	if err != nil {
		return fmt.Errorf("opening release checksums: %w", err)
	}
	defer f.Close()
	sums, err := packageSums(version, f)
	if err != nil {
		return err
	}
	data := struct {
		Version string
		Sums    map[string]string
	}{version, sums}
	for _, recipe := range []struct{ path, text string }{
		{"homebrew/Formula/lazyagents.rb", brewRecipe},
		{"aur/lazyagents-bin/PKGBUILD", aurRecipe},
	} {
		var buf bytes.Buffer
		if err := template.Must(template.New(recipe.path).Parse(recipe.text)).Execute(&buf, data); err != nil {
			return err
		}
		if err := fsutil.WriteAtomic(filepath.Join(out, recipe.path), buf.Bytes(), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", recipe.path, err)
		}
	}
	fmt.Println("Recipes updated; regenerate .SRCINFO with makepkg --printsrcinfo before committing")
	return nil
}

const brewRecipe = `# Generated by scripts/update-packages.go from the release SHA256SUMS.
class Lazyagents < Formula
  desc "Terminal workspace for AI coding agents"
  homepage "https://github.com/rogeriojunior31/lazyagents"
  version "{{.Version}}"
  license all_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "https://github.com/rogeriojunior31/lazyagents/releases/download/v{{.Version}}/lazyagents_{{.Version}}_darwin_arm64.tar.gz"
      sha256 "{{.Sums.darwin_arm64}}"
    end
    on_intel do
      url "https://github.com/rogeriojunior31/lazyagents/releases/download/v{{.Version}}/lazyagents_{{.Version}}_darwin_amd64.tar.gz"
      sha256 "{{.Sums.darwin_amd64}}"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/rogeriojunior31/lazyagents/releases/download/v{{.Version}}/lazyagents_{{.Version}}_linux_arm64.tar.gz"
      sha256 "{{.Sums.linux_arm64}}"
    end
    on_intel do
      url "https://github.com/rogeriojunior31/lazyagents/releases/download/v{{.Version}}/lazyagents_{{.Version}}_linux_amd64.tar.gz"
      sha256 "{{.Sums.linux_amd64}}"
    end
  end

  def install
    bin.install "lazyagents"
    doc.install "README.md"
    pkgshare.install "LICENSE", "internal/tui/theme/LICENSE-SP-Night", "internal/tui/theme/LICENSES-themes.md"
  end

  test do
    assert_equal "lazyagents #{version}\n", shell_output("#{bin}/lazyagents --version")
  end
end
`

